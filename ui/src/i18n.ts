const DICTIONARIES: Record<Lang, Dictionary> = { ko, en, ja, fr }

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string

export function translator(lang: Lang): Translate {
  const dictionary = DICTIONARIES[lang]

  return (key, vars) => {
    const text = dictionary[key]

    return vars === undefined ? text : text.replace(/\{(\w+)\}/g, (whole, name: string) => String(vars[name] ?? whole))
  }
}

export function detectLang(): Lang {
  const tag = navigator.language.toLowerCase()

  if (tag.startsWith('ko')) return 'ko'
  if (tag.startsWith('ja')) return 'ja'
  if (tag.startsWith('fr')) return 'fr'

  return 'en'
}

export function isLang(value: string): value is Lang {
  return LANGS.some(lang => lang.id === value)
}

export const I18nContext = createContext<{ lang: Lang; t: Translate }>({ lang: 'ko', t: translator('ko') })

export function useI18n(): { lang: Lang; t: Translate } {
  return useContext(I18nContext)
}

// Durations and "ago" read naturally in each language through the dictionary.
export function duration(t: Translate, ms: number): string {
  const seconds = Math.max(0, Math.floor(ms / 1000))
  const minutes = Math.floor(seconds / 60)
  const hours = Math.floor(minutes / 60)

  if (seconds < 60) return t('time.s', { s: seconds })
  if (minutes < 60) return t('time.ms', { m: minutes, s: seconds % 60 })
  if (hours < 24) return t('time.hm', { h: hours, m: minutes % 60 })

  return t('time.dh', { d: Math.floor(hours / 24), h: hours % 24 })
}

export function ago(t: Translate, ms: number): string {
  const seconds = Math.max(0, Math.floor(ms / 1000))

  if (seconds < 10) return t('time.justNow')
  if (seconds < 60) return t('time.secondsAgo', { n: seconds })
  if (seconds < 3600) return t('time.minutesAgo', { n: Math.floor(seconds / 60) })

  return t('time.hoursAgo', { n: Math.floor(seconds / 3600) })
}
